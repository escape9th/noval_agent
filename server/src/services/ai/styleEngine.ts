export function initializePresetStyles(userId: number) {
  const db = getDb();
  const existing = db.prepare('SELECT COUNT(*) as count FROM style_profiles WHERE user_id = ? AND type = ?').get(userId, 'preset') as any;
  if (existing.count > 0) return;

  const stmt = db.prepare(`
    INSERT INTO style_profiles (user_id, name, type, description, style_prompt)
    VALUES (?, ?, 'preset', ?, ?)
  `);

  for (const style of PRESET_STYLES) {
    stmt.run(userId, style.name, style.description, style.style_prompt);
  }
}
